/**
 * Слова языка по темам. Одна строка — одно слово: `слово|перевод|как читается`
 * (после чтения можно добавить `|пример|перевод примера`). Пустое «как читается» допустимо.
 */
export type TopicWords = Record<TopicId, string>

/** Разбор блока строк темы. Битые строки (меньше двух полей) пропускаются — их ловит тест каталога. */
export const parseTopicLines = (text: string): VocabularyItemInput[] =>
    text
        .split('\n')
        .map(line => line.trim())
        .filter(Boolean)
        .flatMap(line => {
            const [sourceText, targetText, reading, exampleSource, exampleTarget] = line.split('|').map(p => p.trim())
            if (!sourceText || !targetText) return []
            return [
                {
                    sourceText,
                    targetText,
                    sourceReading: reading || undefined,
                    exampleSource: exampleSource || undefined,
                    exampleTarget: exampleTarget || undefined,
                },
            ]
        })
